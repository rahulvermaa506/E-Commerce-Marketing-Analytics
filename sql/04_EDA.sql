 -- REVENUE BY PRODUCT CATEGORY

 SELECT 
 P.product_category_name ,
 COUNT(DISTINCT OT.product_id) AS UNIQUE_PRODUCTS ,
 COUNT(DISTINCT OT.order_id) AS TOTAL_ORDERS ,
 COUNT(OT.order_id) AS TOTAL_ITEMS_SOLD , 
 SUM(OT.price) AS TOTAL_REVENUE 
 FROM CLEAN.ORDER_ITEMS_CLEAN  OT
 JOIN CLEAN.PRODUCTS_CLEAN P
 ON OT.product_id = P.product_id
 GROUP BY P.product_category_name
 ORDER BY TOTAL_REVENUE DESC;

-- TOP 10 CATEGORY_NAME 
 WITH PRODUCT_CATEGORY AS (
							SELECT 
							P.product_category_name ,
							COUNT(DISTINCT OT.order_id) AS TOTAL_ORDERS ,
							COUNT(OT.order_id) AS TOTAL_ITEMS_SOLD , 
							SUM(OT.price) AS TOTAL_REVENUE
							FROM CLEAN.ORDER_ITEMS_CLEAN  OT
							JOIN CLEAN.PRODUCTS_CLEAN P
							ON OT.product_id = P.product_id
							GROUP BY P.product_category_name
							)

SELECT TOP 10 product_category_name ,
TOTAL_REVENUE,
TOTAL_REVENUE * 100.0 / SUM(TOTAL_REVENUE) OVER() AS CATEGORY_REVENUE_CONTRIBUTION
FROM PRODUCT_CATEGORY 
ORDER BY TOTAL_REVENUE DESC ;






