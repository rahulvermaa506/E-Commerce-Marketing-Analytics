-- CUSTOMER ACQUISITION

WITH CUSTOMER_FIRST_PURCHASE AS 
(
	SELECT 
	C.customer_unique_id ,
	MIN(O.order_purchase_timestamp) AS FIRST_PURCHASE_DATE
	FROM CLEAN.ORDERS_CLEAN O
	INNER JOIN CLEAN.CUSTOMERS_CLEAN C
	ON O.customer_id = C.customer_id
	GROUP BY C.customer_unique_id
)
SELECT 
MONTH(FIRST_PURCHASE_DATE) AS PURCHASE_MONTH ,
YEAR(FIRST_PURCHASE_DATE) AS PURCHASE_YEAR ,
COUNT(*) AS NEW_CUSTOMERS 
FROM CUSTOMER_FIRST_PURCHASE
GROUP BY MONTH(FIRST_PURCHASE_DATE) ,
		 YEAR(FIRST_PURCHASE_DATE) 
ORDER BY PURCHASE_YEAR , PURCHASE_MONTH ;



-- NEW VS EXISTING CUSTOMERS REVENUE 

WITH CUSTOMER_ORDERS AS 
(
	SELECT 
	C.customer_unique_id,
	O.order_id ,
	CAST(O.order_purchase_timestamp AS DATE) AS order_purchase_date
	FROM CLEAN.ORDERS_CLEAN O
	JOIN CLEAN.CUSTOMERS_CLEAN C
	ON O.customer_id = C.customer_id
),
FIRST_PURCHASE AS 
(
	SELECT  
	customer_unique_id ,
	MIN(order_purchase_date) AS FIRST_PURCAHSE_DATE
	FROM CUSTOMER_ORDERS
	GROUP BY customer_unique_id
)

SELECT 

MONTH(CO.order_purchase_date) AS PURCHASE_MONTH,
YEAR(CO.order_purchase_date) AS PURCHASE_YEAR , 
CASE WHEN CO.order_purchase_date = FP.FIRST_PURCAHSE_DATE 
	THEN'NEW CUSTOMER' ELSE 'EXISTING CUSTOMER' END AS CUSTOMER_TYPE ,
SUM(OT.price) AS PRICE

FROM CUSTOMER_ORDERS CO
JOIN FIRST_PURCHASE FP
ON CO.customer_unique_id = FP.customer_unique_id
JOIN CLEAN.ORDER_ITEMS_CLEAN OT
ON CO.order_id = OT.order_id

GROUP BY 
		MONTH(CO.order_purchase_date) ,
		YEAR(CO.order_purchase_date)  , 
		CASE WHEN CO.order_purchase_date = FP.FIRST_PURCAHSE_DATE 
			THEN'NEW CUSTOMER' ELSE 'EXISTING CUSTOMER' END 
ORDER BY 
		PURCHASE_YEAR , PURCHASE_MONTH ;



-- REPEAT CUSTOMER 

WITH CUSTOMER_ORDERS AS (
					SELECT 
					C.customer_unique_id ,
					COUNT( O.order_id) AS TOTAL_ORDERS
					FROM CLEAN.ORDERS_CLEAN O
					JOIN CLEAN.CUSTOMERS_CLEAN AS C
					ON O.customer_id = C.customer_id
					GROUP BY C.customer_unique_id
					)
 SELECT COUNT(*) AS TOTAL_CUSTOMERS,
 SUM(CASE WHEN TOTAL_ORDERS = 1 THEN 1 ELSE 0 END) AS ONE_TIME_CUSTOMERS ,
 SUM(CASE WHEN TOTAL_ORDERS > 1 THEN 1 ELSE 0 END) AS REPEAT_CUSTOMERS
 FROM CUSTOMER_ORDERS  ;
 
